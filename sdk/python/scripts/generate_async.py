"""Mechanical sync -> native async SDK generation. Run after changing client.py; commit the generated module.

Keep request bodies, error handling and method signatures in one source of truth. The transformation only
awaits known I/O calls; response decoding and request construction remain synchronous.
"""

import ast
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1] / "agentbox_sdk"


class Asyncify(ast.NodeTransformer):
    def visit_Name(self, node):
        if node.id == "AgentBox":
            node.id = "AsyncAgentBox"
        return node

    def visit_ClassDef(self, node):
        if node.name == "AgentBoxError":
            return None
        if node.name == "AgentBox":
            node.name = "AsyncAgentBox"
            node.body[0].value.value = (
                "Native asynchronous AgentBox client. All network I/O supports asyncio cancellation."
            )
        for i, fn in enumerate(node.body):
            if not isinstance(fn, ast.FunctionDef) or fn.name == "__init__":
                continue
            fn.name = {"__enter__": "__aenter__", "__exit__": "__aexit__"}.get(fn.name, fn.name)
            node.body[i] = ast.AsyncFunctionDef(
                name=fn.name,
                args=fn.args,
                body=fn.body,
                decorator_list=fn.decorator_list,
                returns=fn.returns,
                type_comment=fn.type_comment,
                type_params=[],
            )
        return self.generic_visit(node)

    def visit_With(self, node):
        self.generic_visit(node)
        return ast.AsyncWith(items=node.items, body=node.body, type_comment=node.type_comment)

    def visit_Expr(self, node):
        if isinstance(node.value, ast.YieldFrom):
            return ast.For(
                target=ast.Name(id="item", ctx=ast.Store()),
                iter=node.value.value,
                body=[ast.Expr(value=ast.Yield(value=ast.Name(id="item", ctx=ast.Load())))],
                orelse=[],
            )
        return self.generic_visit(node)

    def visit_Attribute(self, node):
        if isinstance(node.value, ast.Name) and node.value.id == "httpx":
            node.attr = {"Client": "AsyncClient", "BaseTransport": "AsyncBaseTransport"}.get(node.attr, node.attr)
        return self.generic_visit(node)

    def visit_Call(self, node):
        original = ast.unparse(node.func)
        self.generic_visit(node)
        if original == "time.sleep":
            node.func = ast.Attribute(value=ast.Name(id="asyncio", ctx=ast.Load()), attr="sleep", ctx=ast.Load())
        if original == "self._http.close":
            node.func.attr = "aclose"
        if original in {
            "self._c.request",
            "self.request",
            "self.list",
            "self.upload",
            "self.download_url",
            "self.close",
            "self._http.close",
            "self._http.request",
            "ext.put",
            "ext.get",
            "time.sleep",
        }:
            return ast.Await(value=node)
        return node


tree = Asyncify().visit(ast.parse((PACKAGE / "client.py").read_text()))
# Future imports must precede the additional async/error imports.
tree.body[1:1] = ast.parse("import asyncio\nfrom agentbox_sdk.client import AgentBoxError\n").body
ast.fix_missing_locations(tree)
(PACKAGE / "async_client.py").write_text(
    "# Generated by scripts/generate_async.py; edit client.py instead.\n" + ast.unparse(tree) + "\n"
)
